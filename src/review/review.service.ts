// src/review/review.service.ts
//
// Round 2 Milestone 3: reusable two-way clarification workflow. See the
// ReviewClarification model comment in schema.prisma for why this is
// generic (subjectType/subjectId) rather than hard-wired to User KYC.
import {
  Injectable, NotFoundException, ForbiddenException, BadRequestException,
  UnauthorizedException,
} from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import { ConfigService } from '@nestjs/config';
import { PrismaService } from '../prisma/prisma.service';
import { ClarificationStatus, NotificationType } from '@prisma/client';
import { IsString, IsIn, MinLength, MaxLength, IsOptional, Matches } from 'class-validator';
import { NotificationsService } from '../notifications/notifications.service';
import { destination } from '../notifications/destinations';

// Allow-list of subject types this endpoint accepts. USER_KYC was the
// only one wired up in Milestone 3; Milestone 6 (Round 2) adds the three
// provider profile types below — reusing this exact same clarification
// thread/attachment/token machinery for provider listing review, which
// is exactly why this was built generic in the first place (see
// ReviewClarification's model comment in schema.prisma).
const SUPPORTED_SUBJECT_TYPES = [
  'USER_KYC',
  'WAREHOUSE_PROFILE',
  'TESTING_AGENCY_PROFILE',
  'TRANSPORT_PROFILE',
] as const;

export class CreateClarificationDto {
  @IsIn(SUPPORTED_SUBJECT_TYPES) subjectType: string;
  @IsString() subjectId: string;
  @IsString() @MinLength(5) requestMessage: string;
}

export class RespondClarificationDto {
  @IsString() @MinLength(2) @MaxLength(4000) responseMessage: string;

  // Idempotency key generated by the client once per "Send" intent. A retry
  // or double-click with the same key returns the already-stored message
  // instead of creating a second one.
  @IsOptional() @IsString() @MaxLength(100) @Matches(/^[A-Za-z0-9_-]+$/) clientRequestId?: string;
}

@Injectable()
export class ReviewService {
  private readonly FILE_TOKEN_TTL = '5m';

  constructor(
    private prisma: PrismaService,
    private jwt: JwtService,
    private config: ConfigService,
    private notifications: NotificationsService,
  ) {}

  // Resolves "who is allowed to respond to / view this subject" — the
  // single place that needed a new case for Milestone 6's three provider
  // profile types. For all of them `subjectId` is the profile's own
  // `.id` (matching how every existing admin route for these profiles
  // — adminSetActive, adminVerify, etc. — already addresses them), NOT
  // the operator's `userId`; the owner is resolved via the profile's
  // `userId` column instead.
  private async resolveSubjectOwnerId(subjectType: string, subjectId: string): Promise<string> {
    switch (subjectType) {
      case 'USER_KYC': {
        const user = await this.prisma.user.findUnique({ where: { id: subjectId }, select: { id: true } });
        if (!user) throw new NotFoundException('Subject not found');
        return user.id;
      }
      case 'WAREHOUSE_PROFILE': {
        const profile = await this.prisma.warehouseProfile.findUnique({ where: { id: subjectId }, select: { userId: true } });
        if (!profile) throw new NotFoundException('Subject not found');
        return profile.userId;
      }
      case 'TESTING_AGENCY_PROFILE': {
        const profile = await this.prisma.testingAgencyProfile.findUnique({ where: { id: subjectId }, select: { userId: true } });
        if (!profile) throw new NotFoundException('Subject not found');
        return profile.userId;
      }
      case 'TRANSPORT_PROFILE': {
        const profile = await this.prisma.transportProfile.findUnique({ where: { id: subjectId }, select: { userId: true } });
        if (!profile) throw new NotFoundException('Subject not found');
        return profile.userId;
      }
      default:
        throw new BadRequestException(`Unsupported subject type: ${subjectType}`);
    }
  }

  // ─── ADMIN/MODERATOR: open a clarification request ─────────────────────
  async requestClarification(requestedById: string, dto: CreateClarificationDto) {
    const ownerId = await this.resolveSubjectOwnerId(dto.subjectType, dto.subjectId); // 404s if subject doesn't exist

    const clarification = await this.prisma.reviewClarification.create({
      data: {
        subjectType: dto.subjectType,
        subjectId: dto.subjectId,
        requestedById,
        requestMessage: dto.requestMessage,
        status: ClarificationStatus.OPEN,
        // First message of the thread = the request itself.
        messages: {
          create: { senderId: requestedById, senderRole: 'REVIEWER', body: dto.requestMessage },
        },
      },
    });

    if (dto.subjectType === 'USER_KYC') {
      await this.prisma.user.update({
        where: { id: dto.subjectId },
        data: {
          kycStatus: 'INFO_REQUESTED',
          // Denormalized "latest request" cache — see schema.prisma comment.
          kycInfoRequestNote: dto.requestMessage,
          kycInfoRequestedAt: clarification.createdAt,
        },
      });
    }
    // Provider profile clarifications (Milestone 6) are deliberately
    // communication-only — unlike KYC, `isActive`/`isVerified` on
    // WarehouseProfile/TestingAgencyProfile/TransportProfile are plain
    // admin-controlled booleans, not a review-state machine, so opening
    // a clarification here has no automatic side effect on them. An
    // admin can still flip `isActive`/`isVerified` separately (e.g. to
    // unlist a listing while its clarification is outstanding) — that's
    // just not implied by asking a question.

    await this.notifySubject(ownerId, clarification.subjectType, clarification.id, 'More information needed', dto.requestMessage);
    return clarification;
  }

  // Where the person under review answers: KYC → Account page, provider
  // listings → the matching operator portal's review tab.
  private clarificationDestination(subjectType: string, clarificationId: string, forReviewer: boolean, subjectId?: string) {
    // Reviewer side: a KYC thread opens that person's review dialog (the subject
    // id of a USER_KYC thread IS the user id); provider threads open Users.
    if (forReviewer) {
      return subjectType === 'USER_KYC' && subjectId
        ? destination('/admin', { tab: 'users', entityType: 'kyc', entityId: subjectId })
        : destination('/admin', { tab: 'users', entityType: 'clarification', entityId: clarificationId });
    }
    switch (subjectType) {
      case 'WAREHOUSE_PROFILE': return destination('/warehouse-portal', { tab: 'review', entityType: 'clarification', entityId: clarificationId });
      case 'TESTING_AGENCY_PROFILE': return destination('/testing-portal', { entityType: 'clarification', entityId: clarificationId });
      case 'TRANSPORT_PROFILE': return destination('/transport-portal', { entityType: 'clarification', entityId: clarificationId });
      default: return destination('/account', { tab: 'profile', entityType: 'clarification', entityId: clarificationId });
    }
  }

  private notifTypeFor(subjectType: string): NotificationType {
    switch (subjectType) {
      case 'WAREHOUSE_PROFILE': return NotificationType.WAREHOUSE_UPDATE;
      case 'TESTING_AGENCY_PROFILE': return NotificationType.TESTING_UPDATE;
      case 'TRANSPORT_PROFILE': return NotificationType.TRANSPORT_UPDATE;
      default: return NotificationType.KYC_UPDATE;
    }
  }

  private async notifySubject(ownerId: string, subjectType: string, clarificationId: string, title: string, body: string) {
    await this.notifications.notify({
      userId: ownerId, type: this.notifTypeFor(subjectType), title,
      body: body.length > 140 ? `${body.slice(0, 137)}…` : body,
      data: this.clarificationDestination(subjectType, clarificationId, false),
    });
  }

  // ─── Thread helpers ─────────────────────────────────────────────────────
  // Rows created before the message table existed (or on a database that
  // was updated with `db push` and not back-filled) have no messages. They
  // are presented as a synthetic two-message thread so nothing disappears,
  // and persisted the first time anyone writes to them.
  private legacyMessages(c: any, ownerId: string) {
    const out: any[] = [{
      id: `legacy-req-${c.id}`, clarificationId: c.id, senderId: c.requestedById, senderRole: 'REVIEWER',
      body: c.requestMessage, createdAt: c.createdAt, attachments: [], legacy: true,
    }];
    if (c.responseMessage) {
      out.push({
        id: `legacy-res-${c.id}`, clarificationId: c.id, senderId: ownerId, senderRole: 'SUBJECT',
        body: c.responseMessage, createdAt: c.respondedAt || c.createdAt,
        attachments: c.attachments || [], legacy: true,
      });
    }
    return out;
  }

  private async persistLegacyIfNeeded(tx: any, c: any, ownerId: string) {
    const existing = await tx.reviewClarificationMessage.count({ where: { clarificationId: c.id } });
    if (existing > 0) return;
    await tx.reviewClarificationMessage.create({
      data: { clarificationId: c.id, senderId: c.requestedById, senderRole: 'REVIEWER', body: c.requestMessage, createdAt: c.createdAt },
    });
    if (c.responseMessage) {
      const m = await tx.reviewClarificationMessage.create({
        data: { clarificationId: c.id, senderId: ownerId, senderRole: 'SUBJECT', body: c.responseMessage, createdAt: c.respondedAt || c.createdAt },
      });
      await tx.clarificationAttachment.updateMany({ where: { clarificationId: c.id, messageId: null }, data: { messageId: m.id } });
    }
  }

  // Adds sender display names and a stable, chronological `messages` array.
  private async withThread(clarifications: any[]) {
    const owners = new Map<string, string>();
    for (const c of clarifications) {
      if (!c.messages?.length) owners.set(c.id, await this.resolveSubjectOwnerId(c.subjectType, c.subjectId));
    }
    const shaped = clarifications.map((c) => {
      const messages = c.messages?.length ? c.messages : this.legacyMessages(c, owners.get(c.id) as string);
      return { ...c, messages };
    });
    const ids = Array.from(new Set(shaped.flatMap((c) => c.messages.map((m: any) => m.senderId))));
    const users = ids.length
      ? await this.prisma.user.findMany({ where: { id: { in: ids } }, select: { id: true, role: true, profile: { select: { fullName: true } } } })
      : [];
    const byId = new Map<string, any>((users || []).map((u: any) => [u.id, u]));
    return shaped.map((c) => ({
      ...c,
      messages: [...c.messages]
        .sort((a: any, b: any) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime())
        .map((m: any) => ({
          ...m,
          senderName: byId.get(m.senderId)?.profile?.fullName || (m.senderRole === 'REVIEWER' ? 'AgriConnect review team' : 'Applicant'),
        })),
    }));
  }

  // ─── SUBJECT (or admin/moderator): add a message, optionally with files ─
  async respondToClarification(
    userId: string,
    role: string,
    clarificationId: string,
    dto: RespondClarificationDto,
    files: Array<{ originalname: string; filename: string }> = [],
  ) {
    const clarification = await this.prisma.reviewClarification.findUnique({ where: { id: clarificationId } });
    if (!clarification) throw new NotFoundException('Clarification request not found');

    const ownerId = await this.resolveSubjectOwnerId(clarification.subjectType, clarification.subjectId);
    const isOwner = ownerId === userId;
    const isReviewer = role === 'ADMIN' || role === 'MODERATOR';
    if (!isOwner && !isReviewer) throw new ForbiddenException('Access denied');

    const clientRequestId = dto.clientRequestId || null;

    // Idempotent replay: this exact submit already succeeded (the client
    // retried after a timeout, or the user double-clicked). Return the
    // current thread; do NOT write a second message and do NOT error.
    if (clientRequestId) {
      const prior = await this.prisma.reviewClarificationMessage.findUnique({
        where: { clarificationId_clientRequestId: { clarificationId, clientRequestId } },
      });
      if (prior) return { ...(await this.getOne(clarificationId)), replayed: true };
    }

    if (clarification.status === ClarificationStatus.RESOLVED) {
      throw new BadRequestException('This request has already been resolved and can no longer be responded to');
    }

    const senderRole = isOwner ? 'SUBJECT' : 'REVIEWER';

    try {
      await this.prisma.$transaction(async (tx: any) => {
        await this.persistLegacyIfNeeded(tx, clarification, ownerId);

        const message = await tx.reviewClarificationMessage.create({
          data: { clarificationId, senderId: userId, senderRole, body: dto.responseMessage, clientRequestId },
        });

        if (files.length) {
          await tx.clarificationAttachment.createMany({
            data: files.map((f) => ({
              clarificationId, messageId: message.id, uploadedById: userId,
              fileName: f.originalname, s3Key: f.filename,
            })),
          });
        }

        if (senderRole === 'SUBJECT') {
          await tx.reviewClarification.update({
            where: { id: clarificationId },
            data: { status: ClarificationStatus.RESPONDED, responseMessage: dto.responseMessage, respondedAt: new Date() },
          });
          // Only an account the admin parked at INFO_REQUESTED goes back into
          // the review queue. The old code set SUBMITTED unconditionally,
          // which would also have demoted an APPROVED account that happened
          // to answer a provider/KYC follow-up. The status change is also
          // what used to log the user out on the very next request (it left
          // the allowed-session list); sessions now survive every KYC state.
          if (clarification.subjectType === 'USER_KYC') {
            await tx.user.updateMany({ where: { id: ownerId, kycStatus: 'INFO_REQUESTED' }, data: { kycStatus: 'SUBMITTED' } });
          }
        } else {
          // A reviewer follow-up hands the ball back to the subject.
          await tx.reviewClarification.update({
            where: { id: clarificationId },
            data: { status: ClarificationStatus.OPEN },
          });
          if (clarification.subjectType === 'USER_KYC') {
            await tx.user.updateMany({
              where: { id: ownerId, kycStatus: { in: ['SUBMITTED', 'RECOMMENDED'] } },
              data: { kycStatus: 'INFO_REQUESTED', kycInfoRequestNote: dto.responseMessage, kycInfoRequestedAt: new Date() },
            });
          }
        }
      });
    } catch (err: any) {
      // Two identical submits raced past the check above: the unique index
      // let exactly one through. The loser is a success, not an error.
      if (err?.code === 'P2002' && clientRequestId) {
        return { ...(await this.getOne(clarificationId)), replayed: true };
      }
      throw err;
    }

    // Best-effort notifications; never fail the reply.
    if (senderRole === 'SUBJECT') {
      await this.notifications.notify({
        userId: clarification.requestedById,
        type: this.notifTypeFor(clarification.subjectType),
        title: 'Applicant replied to your request',
        body: dto.responseMessage.length > 140 ? `${dto.responseMessage.slice(0, 137)}…` : dto.responseMessage,
        data: this.clarificationDestination(clarification.subjectType, clarificationId, true, clarification.subjectId),
      });
    } else {
      await this.notifySubject(ownerId, clarification.subjectType, clarificationId, 'New message from the review team', dto.responseMessage);
    }

    return this.getOne(clarificationId);
  }

  private async getOne(clarificationId: string) {
    const c = await this.prisma.reviewClarification.findUnique({
      where: { id: clarificationId },
      include: { attachments: true, messages: { include: { attachments: true }, orderBy: { createdAt: 'asc' } } },
    });
    if (!c) throw new NotFoundException('Clarification request not found');
    return (await this.withThread([c]))[0];
  }

  // ─── ADMIN/MODERATOR: mark resolved (used to help decide approve/reject) ─
  async resolveClarification(resolvedById: string, clarificationId: string) {
    const clarification = await this.prisma.reviewClarification.findUnique({ where: { id: clarificationId } });
    if (!clarification) throw new NotFoundException('Clarification request not found');

    return this.prisma.reviewClarification.update({
      where: { id: clarificationId },
      data: { status: ClarificationStatus.RESOLVED, resolvedById, resolvedAt: new Date() },
    });
  }

  // ─── Full thread for a subject (owner, or admin/moderator) ─────────────
  async listForSubject(subjectType: string, subjectId: string, requesterId: string, requesterRole: string) {
    const ownerId = await this.resolveSubjectOwnerId(subjectType, subjectId);
    const isOwner = ownerId === requesterId;
    const isReviewer = requesterRole === 'ADMIN' || requesterRole === 'MODERATOR';
    if (!isOwner && !isReviewer) throw new ForbiddenException('Access denied');

    const rows = await this.prisma.reviewClarification.findMany({
      where: { subjectType, subjectId },
      include: { attachments: true, messages: { include: { attachments: true }, orderBy: { createdAt: 'asc' } } },
      orderBy: { createdAt: 'asc' },
    });
    return this.withThread(rows);
  }

  // Convenience for the most common case: "my own KYC clarification thread".
  async listMyKycClarifications(userId: string) {
    return this.listForSubject('USER_KYC', userId, userId, 'BUYER'); // role arg unused when isOwner is already true
  }

  // Convenience for a provider operator's own listing clarification
  // thread(s). Needs the profile's `.id` (not `userId`) as subjectId, and
  // needs to look that profile up first since the operator only knows "I
  // am this user", not "my warehouse profile has this id". A warehouse
  // operator can now own more than one warehouse (NEW_Changes item 10),
  // so this fans out across all of them and merges the threads.
  async listMyProviderClarifications(
    userId: string,
    subjectType: 'WAREHOUSE_PROFILE' | 'TESTING_AGENCY_PROFILE' | 'TRANSPORT_PROFILE',
  ) {
    const profileIds = await this.findOwnProviderProfileIds(userId, subjectType);
    if (!profileIds.length) return [];
    const threads = await Promise.all(
      profileIds.map((id) => this.listForSubject(subjectType, id, userId, 'BUYER')), // role arg unused when isOwner is already true
    );
    return threads.flat().sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime());
  }

  private async findOwnProviderProfileIds(
    userId: string,
    subjectType: 'WAREHOUSE_PROFILE' | 'TESTING_AGENCY_PROFILE' | 'TRANSPORT_PROFILE',
  ): Promise<string[]> {
    switch (subjectType) {
      case 'WAREHOUSE_PROFILE': {
        // findMany, not findUnique — userId is no longer unique on
        // WarehouseProfile (an operator can run several warehouses).
        const rows = await this.prisma.warehouseProfile.findMany({ where: { userId }, select: { id: true } });
        return rows.map((r) => r.id);
      }
      case 'TESTING_AGENCY_PROFILE': {
        const p = await this.prisma.testingAgencyProfile.findUnique({ where: { userId }, select: { id: true } });
        return p ? [p.id] : [];
      }
      case 'TRANSPORT_PROFILE': {
        const p = await this.prisma.transportProfile.findUnique({ where: { userId }, select: { id: true } });
        return p ? [p.id] : [];
      }
    }
  }

  // ─── Signed, short-lived, single-file access token (same pattern as
  // AuthService.getKycDocumentSignedUrl / resolveKycFileToken) ────────────
  async getAttachmentSignedUrl(attachmentId: string, requesterId: string, requesterRole: string) {
    const attachment = await this.prisma.clarificationAttachment.findUnique({
      where: { id: attachmentId },
      include: { clarification: true },
    });
    if (!attachment) throw new NotFoundException('Attachment not found');

    const ownerId = await this.resolveSubjectOwnerId(
      attachment.clarification.subjectType,
      attachment.clarification.subjectId,
    );
    const isOwner = ownerId === requesterId;
    const isReviewer = requesterRole === 'ADMIN' || requesterRole === 'MODERATOR';
    if (!isOwner && !isReviewer) throw new ForbiddenException('You do not have permission to view this file');

    const token = this.jwt.sign(
      { sub: attachment.id, purpose: 'clarification_file_access' },
      { secret: this.config.get('JWT_SECRET'), expiresIn: this.FILE_TOKEN_TTL },
    );
    return { url: `/review/clarifications/attachments/file/${token}` };
  }

  // Round 2, Milestone 4: previously resolved to a local disk path; now
  // returns the bucket key itself, which the controller turns into a
  // short-lived presigned bucket URL via StorageService — see
  // AuthService.resolveKycFileToken for the mirrored KYC-side change.
  async resolveFileToken(token: string): Promise<{ s3Key: string; fileName: string }> {
    let payload: any;
    try {
      payload = this.jwt.verify(token, { secret: this.config.get('JWT_SECRET') });
    } catch {
      throw new UnauthorizedException('This file link has expired. Please request it again.');
    }
    if (payload?.purpose !== 'clarification_file_access') {
      throw new UnauthorizedException('Invalid file link.');
    }

    const attachment = await this.prisma.clarificationAttachment.findUnique({ where: { id: payload.sub } });
    if (!attachment) throw new NotFoundException('File not found');

    // s3Key is server-generated (see s3-multer-storage.ts) — always
    // "<folder>/<generated-name>" — never user input. A "/" is now
    // expected (separates the bucket folder from the filename); only
    // ".." is refused as defense in depth against path traversal.
    if (attachment.s3Key.includes('..')) {
      throw new NotFoundException('File not found');
    }

    return {
      s3Key: attachment.s3Key,
      fileName: attachment.fileName,
    };
  }
}
